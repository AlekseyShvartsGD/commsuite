# Installs a logon autostart entry that starts the Commsuite server stack
# (TURN + Node + CloudPub) and publishes its public URL, so the server is
# reachable and discoverable without manually running start-all.ps1.
#
# Per-user Startup folder + a hidden VBS launcher: no administrator rights
# needed and no console window flash at logon.
#
#   powershell -ExecutionPolicy Bypass -File .\server\turn\install-autostart.ps1
#   powershell -ExecutionPolicy Bypass -File .\server\turn\install-autostart.ps1 -Remove
param([switch]$Remove)

$scriptPath = Join-Path $PSScriptRoot 'start-all.ps1'
$startup = [Environment]::GetFolderPath('Startup')
$vbsPath = Join-Path $startup 'Commsuite Server.vbs'

if ($Remove) {
  if (Test-Path -LiteralPath $vbsPath) {
    Remove-Item -LiteralPath $vbsPath -Force
    Write-Host "Removed autostart entry '$vbsPath'."
  } else {
    Write-Host "Autostart entry was not installed."
  }
  return
}

$command = "powershell.exe -NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File ""$scriptPath"""
$vbs = @"
' Auto-generated by server\turn\install-autostart.ps1 - do not edit by hand.
CreateObject("WScript.Shell").Run "$($command -replace '"','""')", 0, False
"@

Set-Content -LiteralPath $vbsPath -Value $vbs -Encoding ASCII
Write-Host "Installed autostart entry '$vbsPath' -> $scriptPath"
